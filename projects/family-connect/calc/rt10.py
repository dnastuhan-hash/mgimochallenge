import subprocess, re, sys
SS = ["python3", "../../../tools/calc/sample_size.py"]
def ss(p1, p2, weekly, weeks=25):
    out = subprocess.run(SS + ["--p1", str(p1), "--p2", str(p2), "--weekly", str(weekly), "--weeks", str(weeks), "--observe-weeks", "1"],
                         capture_output=True, text=True, check=True).stdout
    g = lambda k: re.search(rf"\| \**{k}\**[^|]*\| \**([^|*]+)\**", out).group(1).strip()
    return g("Нужно на вариант"), g("Недель набора нужно"), g("Наберём за это время"), g("Обнаружимое изменение при доступном наборе")
print("# Ответ на возражения red-team: расчёты (rt10.py)\n")
