"""Охват первого запуска «Сигнала до перебоя» (шаг 07). Параметры — допущения реестра.
Запуск: python3 reach.py > reach_out.md"""
P = {  # name: (base, low, high)
    "groups_end": (8000, 8000, 8000),      # C-005 подключённые на конец года без изменений
    "groups_start": (6500, 6500, 6500),    # C-005 оценка базового года
    "eligible": (0.60, 0.40, 0.80),        # C-038
    "members": (1.8, 1.2, 2.5),            # C-036
    "low_event": (0.25, 0.15, 0.40),       # C-043 доля подходящих групп с событием в месяц
    "restricted": (0.04, 0.02, 0.08),      # C-039 номеров ограничено за месяц из-за исчерпания
    "reduction": (0.25, 0.10, 0.40),       # C-040
    "unpaid": (0.03, 0.01, 0.06),          # C-054 приостановки за неоплату в месяц
}
def calc(i):
    v = {k: x[i] for k, x in P.items()}
    g_s, g_e = v["groups_start"]*v["eligible"], v["groups_end"]*v["eligible"]
    nums = g_e*v["members"]
    return {"Подходящие группы, начало года": g_s, "Подходящие группы, конец года": g_e,
            "Номера участников в подходящих группах, конец года": nums,
            "Групп с событием низкого остатка, в месяц": g_e*v["low_event"],
            "Ограничений по пакету, номеров в месяц": nums*v["restricted"],
            "Предотвращённых ограничений, номеров в месяц": nums*v["restricted"]*v["reduction"],
            "Приостановок за неоплату, номеров в месяц": nums*v["unpaid"]}
names = ["основной", "неблагоприятный", "благоприятный"]
res = [calc(i) for i in range(3)]
print("# Охват первого запуска сигнала (reach.py)\n\nЕдиницы: группы / номера; период — месяц или конец планового года.\n")
print("| Показатель | " + " | ".join(names) + " |\n|---|---|---|---|")
for k in res[0]:
    print(f"| {k} | " + " | ".join(f"{r[k]:,.0f}".replace(",", " ") for r in res) + " |")
