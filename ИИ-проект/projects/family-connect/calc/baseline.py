#!/usr/bin/env python3
"""Разбор исходных показателей брифа (только числа брифа, без допущений).

  python3 projects/family-connect/calc/baseline.py   → baseline_out.md
"""
from pathlib import Path

OUT = Path(__file__).with_name("baseline_out.md")

# Исходная таблица брифа, стр. 3 (C-003…C-007)
plan_b, est_b, nochg, target = {}, {}, {}, {}
plan_b["gp"], est_b["gp"], nochg["gp"], target["gp"] = 282, 275, 279, 285
plan_b["active"], est_b["active"], nochg["active"], target["active"] = 5000, 4000, 5000, 8000
plan_b["groups"], est_b["groups"], nochg["groups"], target["groups"] = 7500, 6500, 8000, 12000
plan_b["owners"], est_b["owners"], nochg["owners"], target["owners"] = 1000, 800, 1000, 2000
plan_b["act14"], est_b["act14"], nochg["act14"], target["act14"] = 0.50, 0.42, 0.45, 0.60
RATE = 500            # руб. ВП за доп. оплаченный месяц номера (C-008)
HH, OWN = 100_000, 40_000  # доступные базы (C-002)

L = ["# Разбор исходных показателей (только числа брифа)", "", "Скрипт: `projects/family-connect/calc/baseline.py`", ""]

# 1. Отставание базового года
L += ["## 1. Отставание базового года (оценка против плана)", "",
      "| Показатель | План | Оценка | Отставание | Отставание, % |", "|---|---|---|---|---|"]
names = {"gp": "Валовая прибыль (млн руб.)", "active": "Активные группы (посл. месяц)", "groups": "Подключённые группы (конец года)",
         "owners": "Подключённые владельцы", "act14": "Активация за 14 дней"}
for k in names:
    d = est_b[k] - plan_b[k]
    pct = d / plan_b[k] * 100
    if k == "act14":
        L.append(f"| {names[k]} | {plan_b[k]:.0%} | {est_b[k]:.0%} | {d * 100:+.0f} п.п. | {pct:+.0f} % |")
    else:
        L.append(f"| {names[k]} | {plan_b[k]:,} | {est_b[k]:,} | {d:+,} | {pct:+.0f} % |".replace(",", " "))

# 2. Доля активных среди подключённых
sh = {n: (d["active"] / d["groups"]) for n, d in (("план баз.", plan_b), ("оценка баз.", est_b), ("без изменений", nochg), ("цель", target))}
L += ["", "## 2. Доля активных среди подключённых групп", "",
      "| Срез | Активные / подключённые | Доля |", "|---|---|---|"]
for n, d in (("план баз.", plan_b), ("оценка баз.", est_b), ("без изменений", nochg), ("цель", target)):
    L.append(f"| {n} | {d['active']:,} / {d['groups']:,} | {sh[n]:.1%} |".replace(",", " "))

# 3. Разложение отставания активных групп базового года
conn_eff = (est_b["groups"] - plan_b["groups"]) * sh["план баз."]
share_eff = est_b["groups"] * (sh["оценка баз."] - sh["план баз."])
L += ["", "## 3. Разложение отставания активных групп базового года (−1 000)", "",
      f"- За счёт меньшего числа подключённых групп: (6 500 − 7 500) × {sh['план баз.']:.1%} = **{conn_eff:+.0f}**",
      f"- За счёт меньшей доли активных: 6 500 × ({sh['оценка баз.']:.1%} − {sh['план баз.']:.1%}) = **{share_eff:+.0f}**",
      f"- Сумма: {conn_eff + share_eff:+.0f} (сверка с −1 000: {'OK' if abs(conn_eff + share_eff + 1000) < 1 else 'ОШИБКА'})",
      "", "Вывод: около двух третей отставания — меньше подключённых групп, треть — реже совершают полезное действие."]

# 4. Что требуют цели планового года
need_share_at_nochg = target["active"] / nochg["groups"]
L += ["", "## 4. Что требуют цели планового года", "",
      f"- Подключённые группы: чистый прирост к началу года {target['groups'] - est_b['groups']:+,} (с 6 500 до 12 000); "
      f"разрыв с прогнозом без изменений {target['groups'] - nochg['groups']:+,}.".replace(",", " "),
      f"- Активные группы: при 8 000 подключённых (без изменений) для 8 000 активных доля должна быть {need_share_at_nochg:.0%} — "
      "невозможно; при 12 000 подключённых нужна доля 66,7 % (сейчас по прогнозу 62,5 %). "
      "**Цель по активным достижима только вместе с ростом подключённых.**",
      f"- Активация: +{(target['act14'] - nochg['act14']) * 100:.0f} п.п. к прогнозу без изменений (45 % → 60 %).",
      f"- Владельцы: {target['owners'] - nochg['owners']:+,} к прогнозу без изменений (удвоение).".replace(",", " "),
      f"- Валовая прибыль: {target['gp'] - nochg['gp']:+} млн руб. = **{(target['gp'] - nochg['gp']) * 1e6 / RATE:,.0f}** доп. оплаченных месяцев "
      "по 500 руб. при отсутствии других вкладов и новых расходов.".replace(",", " ")]

# 5. Проникновение в доступную базу
L += ["", "## 5. Проникновение в доступную базу", "",
      "| | Сейчас (оценка баз.) | Без изменений | Цель |", "|---|---|---|---|",
      f"| Подключённые группы / 100 тыс. домохозяйств | {est_b['groups'] / HH:.1%} | {nochg['groups'] / HH:.1%} | {target['groups'] / HH:.1%} |",
      f"| Подключённые владельцы / 40 тыс. | {est_b['owners'] / OWN:.1%} | {nochg['owners'] / OWN:.1%} | {target['owners'] / OWN:.1%} |",
      "", "Вывод: доступная база не ограничивает рост в плановом году — ограничивает привлечение и подключение."]

OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
print("\n".join(L))
